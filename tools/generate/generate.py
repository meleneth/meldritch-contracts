#!/usr/bin/env python3
"""Generate deterministic TypeScript and LuaLS consumer bindings."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]


def load(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], separators=(",", ":"))
    if "enum" in schema:
        return " | ".join(json.dumps(item, separators=(",", ":")) for item in schema["enum"])
    if "oneOf" in schema:
        return " | ".join(ts_type(item) for item in schema["oneOf"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({"type": item}) for item in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties")
        if properties:
            required = set(schema.get("required", []))
            fields = "; ".join(
                f"{name}{'' if name in required else '?'}: {ts_type(value)}"
                for name, value in properties.items()
            )
            return "{ " + fields + " }"
        return "Record<string, unknown>"
    return "unknown"


def generate_typescript() -> str:
    path = ROOT / "web/schemas/protocol.schema.json"
    schema = load(path)
    version = load(ROOT / "web/protocol.yaml")["version"]
    lines = [
        "// Generated by tools/generate/generate.py; DO NOT EDIT.",
        f"// Contract: meldritch-web-protocol {version}",
        f"// Source: web/schemas/protocol.schema.json sha256:{digest(path)}",
        "",
    ]
    for name, definition in schema["$defs"].items():
        if definition.get("type") == "object" and "properties" in definition:
            lines.append(f"export interface {name} {{")
            required = set(definition.get("required", []))
            for field, value in definition["properties"].items():
                optional = "" if field in required else "?"
                lines.append(f"  {field}{optional}: {ts_type(value)};")
            if definition.get("additionalProperties") is True:
                lines.append("  [key: string]: unknown;")
            lines.append("}")
        else:
            lines.append(f"export type {name} = {ts_type(definition)};")
        lines.append("")
    client = ["Hello", "Authenticate", "ControlSet", "StepToggle", "TriggerFire", "NoteCreate", "NoteUpdate", "NoteDelete", "DrumHitToggle", "DrumHitVelocity", "DrumMute", "PatternSelect", "AdsrSet", "PresetSelect"]
    server = ["HelloAccepted", "ProtocolIncompatible", "Session", "ErrorMessage", "StateSnapshot", "StateUpdated"]
    lines.append("export type ClientMessage = " + " | ".join(client) + ";")
    lines.append("export type ServerMessage = " + " | ".join(server) + ";")
    lines.append("")
    return "\n".join(lines)


def lua_name(value: str) -> str:
    return value.replace("any", "unknown")


def generate_lua() -> str:
    path = ROOT / "lua/api.yaml"
    api = load(path)
    lines = [
        "---@meta",
        "-- Generated by tools/generate/generate.py; DO NOT EDIT.",
        f"-- Contract: meldritch-lua-host-api {api['version']}",
        f"-- Source: lua/api.yaml sha256:{digest(path)}",
        "",
    ]
    for name, definition in api["types"].items():
        lines.append(f"---@class {name}")
        for field, field_type in definition.get("fields", {}).items():
            optional = field_type.endswith("?")
            base = field_type[:-1] if optional else field_type
            lines.append(f"---@field {field} {lua_name(base)}{'|nil' if optional else ''}")
        lines.append("")
    for namespace in api["namespaces"]:
        name = namespace["name"]
        lines.append(f"---@class {name}")
        for operation in namespace["operations"]:
            args = []
            for argument in operation.get("arguments", []):
                arg_name, _, arg_type = argument.partition(":")
                args.append(f"fun({arg_name}: {lua_name(arg_type or 'unknown')})")
            returns = operation.get("returns", [])
            suffix = f": {lua_name(returns[0])}" if returns else ""
            lines.append(f"---@field {operation['name']} {args[0] if len(args) == 1 else 'function'}{suffix}")
        lines.append("")
    lines.extend(["---@type meldritch", "meldritch = meldritch or {}", "", "return meldritch", ""])
    return "\n".join(lines)


def update(path: Path, content: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return True
    if check:
        print(f"stale generated file: {path.relative_to(ROOT)}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"generated {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    ok = update(ROOT / "web/generated/protocol.ts", generate_typescript(), arguments.check)
    ok &= update(ROOT / "lua/types/meldritch.lua", generate_lua(), arguments.check)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
